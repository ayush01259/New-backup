import numpy as np 
array = np.array([12, 45, 67, 23, 89, 34,22])
print("The max and the min values of the array are : ", np.min(array), np.max(array))

print("The Mean value of the array is ", np.mean(array), "and the median of the array is ", np.median(array))


print("Standard deviation of the array is :", np.std(array))

print("Max value's index of the array is ", np.argmax(array))

